import { createApiErrorResponse } from "@/server/infrastructure/http/api-response";
import { randomUUID } from "node:crypto";
import { isTrustedSameOriginRequest } from "@/server/infrastructure/http/same-origin";
import { provisionTenant } from "@/server/infrastructure/supabase/tenant-provisioning";
import { generateTenantSlug } from "@/modules/identity/domain/tenant-slug";
import { parseTenantProvisioningRequest } from "@/modules/identity/application/tenant-provisioning-request";

const PRIVATE_NO_STORE = { "Cache-Control": "private, no-store" };

function errorResponse(status: number, code: string, message: string, requestId: string) {
  return createApiErrorResponse(status, code, message, requestId, PRIVATE_NO_STORE);
}

export async function POST(request: Request) {
  const requestId = randomUUID();
  if (!isTrustedSameOriginRequest(request)) {
    return errorResponse(403, "ORIGIN_NOT_ALLOWED", "Request origin is not allowed.", requestId);
  }
  if (request.headers.get("content-type")?.split(";")[0]?.trim().toLowerCase() !== "application/json") {
    return errorResponse(400, "INVALID_REQUEST", "A JSON body is required.", requestId);
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return errorResponse(400, "INVALID_REQUEST", "The request body must be valid JSON.", requestId);
  }
  const parsedBody = parseTenantProvisioningRequest(body);
  if (!parsedBody) {
    return errorResponse(400, "INVALID_REQUEST", "Provide a valid displayName, reason, and UUID idempotencyKey; the slug is generated by the server.", requestId);
  }

  const slug = generateTenantSlug(parsedBody.displayName);
  if (!slug) {
    return errorResponse(422, "INVALID_REQUEST", "The organization name must generate an identifier with at least 3 letters or numbers.", requestId);
  }

  const result = await provisionTenant({ ...parsedBody, slug }, requestId);
  if (!result.ok) {
    if (result.reason === "unauthenticated") return errorResponse(401, "UNAUTHENTICATED", "Authentication is required.", requestId);
    if (result.reason === "forbidden") return errorResponse(403, "FORBIDDEN", "Tenant provisioning is not permitted.", requestId);
    if (result.reason === "conflict") return errorResponse(409, "CONFLICT", "The Tenant slug or idempotency key conflicts with an existing request.", requestId);
    if (result.reason === "invalid") return errorResponse(422, "INVALID_REQUEST", "The organization name or provisioning request is not valid.", requestId);
    return errorResponse(503, "SERVICE_UNAVAILABLE", "Tenant provisioning is temporarily unavailable.", requestId);
  }

  return Response.json({ tenant: { id: result.tenantId, slug, name: parsedBody.displayName }, correlationId: result.correlationId }, {
    status: 201,
    headers: PRIVATE_NO_STORE,
  });
}
