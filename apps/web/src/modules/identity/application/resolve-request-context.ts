export type ActiveMembershipCandidate = Readonly<{
  membershipId: string;
  actorId: string;
  tenantId: string;
  tenantName: string;
  membershipStatus: string;
  tenantStatus: string;
}>;

export type RequestContext = Readonly<{
  actorId: string;
  tenantId: string;
  tenantName: string;
  membershipId: string;
  correlationId: string;
}>;

export type RequestContextPort = Readonly<{
  getAuthenticatedActorId(): Promise<string | null>;
  listMemberships(actorId: string): Promise<
    | { ok: true; memberships: readonly ActiveMembershipCandidate[] }
    | { ok: false }
  >;
}>;

export type RequestContextResolution =
  | { ok: true; context: RequestContext }
  | {
      ok: false;
      reason: "unauthenticated" | "tenant_selection_required" | "forbidden" | "invalid_tenant" | "context_unavailable";
      correlationId: string;
      availableTenants?: readonly Readonly<{ tenantId: string; name: string }>[];
    };

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID_PATTERN.test(value);
}

/**
 * Resolves the actor and current tenant membership from trusted server ports.
 * The tenant selector is only a selector; it is never accepted as proof of access.
 */
export async function resolveRequestContext(
  port: RequestContextPort,
  tenantSelector: unknown,
  /** Must be generated by the trusted server adapter, never copied from a client header. */
  correlationId: string,
): Promise<RequestContextResolution> {
  let actorId: string | null;
  try {
    actorId = await port.getAuthenticatedActorId();
  } catch {
    return { ok: false, reason: "context_unavailable", correlationId };
  }

  if (!actorId) return { ok: false, reason: "unauthenticated", correlationId };
  if (!isUuid(actorId)) return { ok: false, reason: "context_unavailable", correlationId };
  actorId = actorId.toLowerCase();

  const hasTenantSelector = tenantSelector !== undefined && tenantSelector !== null && tenantSelector !== "";
  if (hasTenantSelector && !isUuid(tenantSelector)) {
    return { ok: false, reason: "invalid_tenant", correlationId };
  }
  const selectedTenantId = hasTenantSelector ? (tenantSelector as string).toLowerCase() : undefined;

  let result: Awaited<ReturnType<RequestContextPort["listMemberships"]>>;
  try {
    result = await port.listMemberships(actorId);
  } catch {
    return { ok: false, reason: "context_unavailable", correlationId };
  }
  if (!result.ok) return { ok: false, reason: "context_unavailable", correlationId };

  const active: ActiveMembershipCandidate[] = [];
  const seenTenantIds = new Set<string>();
  for (const membership of result.memberships) {
    if (!isUuid(membership.actorId) || !isUuid(membership.membershipId) || !isUuid(membership.tenantId)) {
      return { ok: false, reason: "context_unavailable", correlationId };
    }
    const normalizedMembership = {
      ...membership,
      actorId: membership.actorId.toLowerCase(),
      tenantId: membership.tenantId.toLowerCase(),
      membershipId: membership.membershipId.toLowerCase(),
    };
    if (
      normalizedMembership.actorId !== actorId || membership.membershipStatus !== "active" ||
      membership.tenantStatus !== "active"
    ) continue;
    if (seenTenantIds.has(normalizedMembership.tenantId)) {
      return { ok: false, reason: "context_unavailable", correlationId };
    }
    seenTenantIds.add(normalizedMembership.tenantId);
    active.push(normalizedMembership);
  }

  if (hasTenantSelector) {
    const selected = active.find((membership) => membership.tenantId === selectedTenantId);
    if (!selected) return { ok: false, reason: "forbidden", correlationId };
    return {
      ok: true,
      context: {
        actorId,
        tenantId: selected.tenantId,
        tenantName: selected.tenantName,
        membershipId: selected.membershipId,
        correlationId,
      },
    };
  }

  if (active.length === 0) return { ok: false, reason: "forbidden", correlationId };
  if (active.length > 1) {
    return {
      ok: false,
      reason: "tenant_selection_required",
      correlationId,
      availableTenants: active.map(({ tenantId, tenantName }) => ({ tenantId, name: tenantName })),
    };
  }

  const selected = active[0];
  return {
    ok: true,
    context: {
      actorId,
      tenantId: selected.tenantId,
      tenantName: selected.tenantName,
      membershipId: selected.membershipId,
      correlationId,
    },
  };
}
